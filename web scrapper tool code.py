import requests
from bs4 import BeautifulSoup
import pandas as pd

"""Next, let's define a function to perform the web scraping. This function will fetch the content of the given URL and extract text from common elements like paragraphs, headings, and lists. It will return a dictionary of the scraped data."""

def scrape_website_text(url):
    """
    Scrapes text content from a given URL.
    Extracts text from common elements like paragraphs, headings, and list items.
    """
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
    }
    try:
        response = requests.get(url, headers=headers, timeout=10)
        response.raise_for_status()  # Raise an exception for HTTP errors
    except requests.exceptions.RequestException as e:
        print(f"Error fetching URL {url}: {e}")
        return None

    soup = BeautifulSoup(response.text, 'html.parser')

    # Initialize lists to store different types of text
    headings = []
    paragraphs = []
    list_items = []
    all_text = []

    # Extract headings
    for h in soup.find_all(['h1', 'h2', 'h3', 'h4', 'h5', 'h6']):
        text = h.get_text(strip=True)
        if text:
            headings.append(text)
            all_text.append(text)

    # Extract paragraphs
    for p in soup.find_all('p'):
        text = p.get_text(strip=True)
        if text:
            paragraphs.append(text)
            all_text.append(text)

    # Extract list items
    for li in soup.find_all('li'):
        text = li.get_text(strip=True)
        if text:
            list_items.append(text)
            all_text.append(text)

    # Prepare data for DataFrame
    data = {
        'URL': url,
        'Headings': '; '.join(headings),
        'Paragraphs': '\n\n'.join(paragraphs),
        'List Items': '; '.join(list_items),
        'All Extracted Text': '\n\n'.join(all_text) # Combine all text for a general overview
    }
    return data

