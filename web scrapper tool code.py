print(f"Scraping data from: {url_to_scrape}")
scraped_data = scrape_website_text(url_to_scrape)

if scraped_data:
    # Convert the dictionary to a pandas DataFrame
    df_scraped = pd.DataFrame([scraped_data])
    display(df_scraped.head())
else:
    print("No data was scraped or an error occurred.")

"""Finally, we will save the scraped data to a CSV file named `scraped_website_data.csv`."""

